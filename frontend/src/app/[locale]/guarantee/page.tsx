import type {Metadata} from 'next';
import {hasLocale} from 'next-intl';
import {notFound} from 'next/navigation';
import {setRequestLocale} from 'next-intl/server';
import {Link} from '@/i18n/navigation';
import {routing} from '@/i18n/routing';

export async function generateMetadata({
  params,
}: {
  params: Promise<{locale: string}>;
}): Promise<Metadata> {
  const {locale} = await params;
  if (!hasLocale(routing.locales, locale)) return {};

  return {
    title: 'Гарантія',
    description:
      'Гарантія в інтернет-магазині Gadgeto: гарантійні умови на всі товари, мінімальний гарантійний термін 14 календарних днів, що робити при виявленні несправності та на що гарантія не поширюється.',
    alternates: {
      canonical: '/guarantee',
      languages: {uk: '/guarantee', 'x-default': '/guarantee'},
    },
  };
}

