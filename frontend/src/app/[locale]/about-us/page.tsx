export async function generateMetadata({
  params,
}: {
  params: Promise<{locale: string}>;
}): Promise<Metadata> {
  const {locale} = await params;
  if (!hasLocale(routing.locales, locale)) return {};

  return {
    title: 'Про нас',
    description:
      'Про інтернет-магазин Gadgeto: український магазин сучасної електроніки та аксесуарів. Широкий асортимент нової техніки, конкурентні ціни, доставка по всій Україні та професійна підтримка клієнтів.',
    alternates: {
      canonical: '/about-us',
      languages: {uk: '/about-us', 'x-default': '/about-us'},
    },
  };
}

